//vertex shader - processes input vertex data, usually normalizes and transforms input data to coordinates that fall within OpenGL's visible region
std::string vertexShaderProg = R"(#version 330 core
layout (location = 0) in vec3 position; 
layout (location = 1) in vec3 normal; 
layout (location = 2) in vec2 uv; 
uniform mat4 view, projection, model; 
out vec3 fragNormal, fragPosition;
out vec2 fragUV;
void main()
{
	vec4 mPosition = model * vec4(position, 1.0);
	fragPosition = mPosition.xyz;
	mat3 normalMatrix = transpose(inverse(mat3(model)));
	fragNormal = normalMatrix * normal;
	gl_Position = projection * view * mPosition;
	fragUV = uv;
})";

//fragment shader - calculates the color output of our pixels. Processes a fragment generated by the rasterization stage, into a set of colors and a single depth value.
std::string fragmentShaderProg = R"(#version 330 core
in vec3 fragNormal, fragPosition;
in vec2 fragUV;
uniform sampler2D diffuseTex; 
uniform vec4 light; //DONE
uniform vec3 materialSpecularColor, cameraPosition; 
uniform float Kd, Ks, shininess; 
out vec4 outColor;

vec3 computeColor();

void main()
{
	outColor = vec4(computeColor(), 1);
};

vec3 computeColor()
{
	vec4 materialColor = texture(diffuseTex, fragUV);
	vec3 lightVector = light.xyz;
	
	if(light.w > 0)
		lightVector = light.xyz - fragPosition; 

	vec3 L = normalize(lightVector);
	vec3 N = normalize(fragNormal);

	vec3 V = normalize(cameraPosition - fragPosition);
	vec3 H = normalize (L + V);
	
	vec3 ambientLightIntensity = vec3(0.1f, 0.1f, 0.1f);
	vec3 ambientReflection = ambientLightIntensity * vec3(materialColor.xyz);

	vec3 diffuseReflection = Kd * vec3(materialColor.xyz) * clamp(dot(L,N), 0, 1);
	vec3 specularReflection = Ks * materialSpecularColor * pow(clamp(dot(N,H), 0, 1), shininess);

	return diffuseReflection + specularReflection + ambientReflection;
}
)";

