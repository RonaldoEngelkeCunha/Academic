			y = Radius * cos(LatAngle) * sin(LongAngle);
			z = Radius * sin(LatAngle);

			glm::vec3 normal((x * (1.0f) / Radius), (y * (1.0f) / Radius), (z * (1.0f)) / Radius);
			normals.push_back(normal.x);
			normals.push_back(normal.y);
			normals.push_back(normal.z);

