	float Longs = 50;
	float LongsStep; //size of each sector
	float Lats = 50;
	float LatsStep; //size of each stack
	float totalSize = (Longs + 1) * Lats * 2 * 3;

	LongsStep = 2 * Pi / Longs; //calculate the size of each longitude step
	LatsStep = Pi / Lats; //calculate the size of each latitude step

	float LongAngle; //Theta = 2pi * longStep/longCount so also equal to => j * longStep (size)
	float LatAngle; //Phi = (Pi/2 - Pi) * (latStep/latCount) so also equal to => Pi/2 - i * latStep (size)

	const float UnitLat = 1 / (float)(Lats - 1);
	const float UnitLong = 1 / (float)(Longs - 1);

	float normalizedLength = 1.0f;

	//If the Longitude is varying from - 180 to 180 degree then linearly map Longitude = = 180 degree to u = -0.5 and Longitude = 180 to u = 0.5.

	//If the latitude is varying from + 90 to - 90 degrees then linearly map Latitude = -90 degree to v = -0.5 and Latitude = 90 
	//to v = 0.5.If you are using spherical coordinate angles
	//(see https ://en.wikipedia.org/wiki/Spherical_coordinate_systemLinks to an external site.) 
	//then use a similar linear mapping from phi angle to u and theta angle to v.
	std::vector<float> longAngles;
	std::vector<float> testu;
	std::vector<float> testv;

	std::vector<float> latAngles;
	int k0, k1, k2;
